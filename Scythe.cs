public class Scythe : Weapon
{

    public void SharpenScythe()
    {
        sharpness += 5;
    }

    public int GetSharpnessSchythe()
    {
        return sharpness;
    }

    public void HardenScythe()
    {
        hardness += 2;
    }

    public int GetHardnessSchythe()
    {
        return hardness;
    }





}
